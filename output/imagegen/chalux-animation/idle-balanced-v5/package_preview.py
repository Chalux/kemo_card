"""Assemble generated pixel-art layers into an invariant-shading idle loop.

No repainting, palette replacement, interpolation or rescaling is performed.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
from PIL import Image

root = Path(__file__).resolve().parent
sheet = Image.open(root / "generated-sheet.png").convert("RGBA")
assert sheet.size == (1536, 1024)
size = (432, 560)
padding = 24
sources = []
for i in range(8):
    x, y = (i % 4) * 384, (i // 4) * 512
    source = sheet.crop((x, y, x + 384, y + 512))
    padded = Image.new("RGBA", size)
    padded.paste(source, (padding, padding))
    sources.append(padded)

def registration_features(frame):
    rgba = np.asarray(frame, dtype=np.float32)
    # Alpha-weighted colors prevent transparent backdrop RGB from influencing
    # registration. Only the planted paws serve as the stable root landmark.
    return np.concatenate((rgba[:, :, :3] * rgba[:, :, 3:] / 255, rgba[:, :, 3:]), axis=2)

reference = registration_features(sources[0])
region = np.s_[480:536, 174:402, :]
registered = [sources[0]]
offsets = [[0, 0]]
errors = [0.0]
for source in sources[1:7]:
    features = registration_features(source)
    best = None
    for dy in range(-12, 13):
        for dx in range(-12, 13):
            candidate = np.roll(features, (dy, dx), axis=(0, 1))
            error = float(np.mean((candidate[region] - reference[region]) ** 2))
            score = (error, abs(dx) + abs(dy), dx, dy)
            if best is None or score < best:
                best = score
    error, _, dx, dy = best
    aligned = Image.new("RGBA", size)
    aligned.paste(source, (dx, dy))
    registered.append(aligned)
    offsets.append([dx, dy])
    errors.append(error)

# Share one immutable body plate across the entire animation. The artistic edit
# is generated by image_gen; animation assembly only uses its existing pixels.
base = registered[0].copy()
eye_box = (272, 89, 302, 115)
closed_eye = registered[4].crop(eye_box)
tail_box = (60, 424, 164, 504)
tail_source = np.asarray(base.crop(tail_box)).copy()
tail_displacements = [0, 4, 4, 0, -4, 0, 0, 0]
assembled = []
for i, displacement in enumerate(tail_displacements):
    frame = base.copy()
    if i == 4:
        frame.paste(closed_eye, eye_box[:2])
    if displacement:
        # Rigid source colors follow a tiny stepped tail-tip bend. No palette,
        # shading or opacity is regenerated; no interpolation is performed.
        shifted = np.zeros_like(tail_source)
        height, width = tail_source.shape[:2]
        for y in range(height):
            delta = round(displacement * (y // 16) / max(1, (height - 1) // 16))
            if delta >= 0:
                shifted[y, delta:] = tail_source[y, :width - delta]
            else:
                shifted[y, :width + delta] = tail_source[y, -delta:]
        frame.paste(Image.fromarray(shifted), tail_box[:2])
    assembled.append(frame)
registered = assembled
static_mask = np.ones((size[1], size[0]), dtype=bool)
for x0, y0, x1, y1 in (eye_box, tail_box):
    static_mask[y0:y1, x0:x1] = False
base_array = np.asarray(base)
assert all(np.array_equal(np.asarray(frame)[static_mask], base_array[static_mask]) for frame in registered)

# Use the first frame itself as the closing frame. This guarantees the boundary
# is identical, independent of image generation's approximate final pose.
registered[-1] = registered[0].copy()
offsets.append([0, 0])
errors.append(0.0)
assert registered[0].tobytes() == registered[-1].tobytes()

atlas = Image.new("RGBA", (size[0] * 4, size[1] * 2))
preview = []
for i, frame in enumerate(registered):
    frame.save(root / "frames" / f"idle-{i + 1:02d}.png")
    atlas.paste(frame, ((i % 4) * size[0], (i // 4) * size[1]))
    background = Image.new("RGBA", size, (38, 43, 54, 255))
    background.alpha_composite(frame)
    preview.append(background.convert("RGB"))
atlas.save(root / "idle-sheet.png")
# A shared GIF palette also prevents frame-local quantization from producing
# preview-only color shimmer in the otherwise invariant body plate.
palette = preview[0].quantize(colors=256, dither=Image.Dither.NONE)
preview = [frame.quantize(palette=palette, dither=Image.Dither.NONE) for frame in preview]
preview[0].save(root / "idle-preview.gif", save_all=True, append_images=preview[1:], duration=160, loop=0, disposal=2)

manifest = {"animation": "idle", "frameCount": 8, "frameSize": list(size), "columns": 4, "rows": 2, "fps": 6.25, "loop": True, "status": "awaiting-user-confirmation", "rootMotion": False, "firstLastIdentical": True, "staticRegionPixelIdentical": True, "animatedRegions": {"eye": list(eye_box), "tailTip": list(tail_box)}, "tailTipMaxDisplacementPx": 4, "firstLastSha256": hashlib.sha256(registered[0].tobytes()).hexdigest(), "integerRegistrationOffsets": offsets, "generatedWith": "built-in image_gen", "processing": "generated art assembled as one immutable body layer plus cropped blink and integer tail-tip deformation; no repainting, palette changes or interpolation"}
(root / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
print(json.dumps(manifest, ensure_ascii=False))
